#[test]
fn bind_file_outside_a_repo_stops_at_the_ceiling_and_writes_no_exclude_file() {
    let h = home();
    let dir = h.dir.path().join("plain");
    std::fs::create_dir_all(&dir).unwrap();
    // Any repo above the temp folder (such as a home folder that is a repo) must stay untouched.
    let above: Vec<_> = h
        .dir
        .path()
        .ancestors()
        .skip(1)
        .map(|d| d.join(".git").join("info").join("exclude"))
        .map(|f| (std::fs::metadata(&f).ok().map(|m| m.len()), f))
        .collect();
    h.hydra()
        .args(["bind", "--file"])
        .arg(&dir)
        .arg("work")
        .assert()
        .success()
        .stdout(predicate::str::contains("added to").not());
    for (len, f) in above {
        assert_eq!(std::fs::metadata(&f).ok().map(|m| m.len()), len, "{f:?}");
    }
    assert!(!h.dir.path().join(".git").exists());
}

fn bound_folder(h: &Home, sub: &str, env: &str) -> std::path::PathBuf {
    let d = h.dir.path().join(sub);
    std::fs::create_dir_all(&d).unwrap();
    h.hydra().arg("bind").arg(&d).arg(env).assert().success();
    d
}

#[test]
fn shell_without_a_name_uses_the_folders_binding() {
    let h = home();
    let d = bound_folder(&h, "w", "work");
    h.hydra()
        .current_dir(&d)
        .args(["shell", "--shell", "pwsh"])
        .write_stdin("exit 0\n")
        .assert()
        .success()
        .stderr(predicate::str::contains("opening work (rule"));
}

