use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellKind {
    Pwsh,
    Bash,
    Zsh,
}

impl ShellKind {
    pub fn parse(s: &str) -> Option<Self> {
        match s.to_ascii_lowercase().as_str() {
            "pwsh" | "powershell" => Some(Self::Pwsh),
            "bash" => Some(Self::Bash),
            "zsh" => Some(Self::Zsh),
            _ => None,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Pwsh => "pwsh",
            Self::Bash => "bash",
            Self::Zsh => "zsh",
        }
    }

    /// The shell used when none is configured: pwsh on Windows, zsh (the login shell macOS
    /// ships) on macOS, bash elsewhere.
    pub fn platform_default() -> Self {
        if cfg!(windows) {
            Self::Pwsh
        } else if cfg!(target_os = "macos") {
            Self::Zsh
        } else {
            Self::Bash
        }
    }
}

pub struct PromptStyle<'a> {
    pub name: &'a str,
    pub rgb: Option<(u8, u8, u8)>,
    /// hydraui: also mark the prompt (OSC 133) and the folder (OSC 7).
    pub integration: bool,
}

pub fn find_shell(kind: ShellKind, git_bash: Option<&Path>) -> Option<PathBuf> {
    match kind {
        ShellKind::Pwsh => {
            crate::process::find_on_path(if cfg!(windows) { "pwsh.exe" } else { "pwsh" })
        }
        ShellKind::Bash => {
            if let Some(p) = git_bash {
                return p.is_file().then(|| p.to_path_buf());
            }
            if cfg!(windows) {
                let p = PathBuf::from(std::env::var_os("ProgramFiles")?)
                    .join("Git")
                    .join("bin")
                    .join("bash.exe");
                p.is_file().then_some(p)
            } else {
                crate::process::find_on_path("bash")
            }
        }
        ShellKind::Zsh => crate::process::find_on_path("zsh").or_else(|| {
            let p = PathBuf::from("/bin/zsh");
            p.is_file().then_some(p)
        }),
    }
}

fn header(name: &str) -> String {
    format!(
        "# generated by hydra for environment \"{name}\" - edit ~/.hydra/envs/{name}/env.toml instead\n"
    )
}

/// `C:\a\b` -> `/c/a/b` (Git Bash form).
pub fn to_msys(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    let b = s.as_bytes();
    if b.len() >= 2 && b[1] == b':' && b[0].is_ascii_alphabetic() {
        format!("/{}{}", (b[0] as char).to_ascii_lowercase(), &s[2..])
    } else {
        s
    }
}

/// PowerShell single-quoted string. PowerShell treats the typographic quotes ‘ ’ ‚ ‛ as
/// single quotes too, so each of them is doubled along with `'`.
pub fn pwsh_quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for c in s.chars() {
        if matches!(c, '\'' | '\u{2018}' | '\u{2019}' | '\u{201a}' | '\u{201b}') {
            out.push(c);
        }
        out.push(c);
    }
    out.push('\'');
    out
}

/// POSIX single-quoted string.
pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

pub fn render_pwsh_init(style: &PromptStyle) -> String {
    let mut s = header(style.name);
    // -NoProfile skips all four profiles, so load them here in pwsh's own order. A foreach
    // statement (not ForEach-Object) keeps the dot-sourcing in the caller's scope.
    s.push_str("foreach ($p in $PROFILE.AllUsersAllHosts, $PROFILE.AllUsersCurrentHost, $PROFILE.CurrentUserAllHosts, $PROFILE.CurrentUserCurrentHost) { if ($p -and (Test-Path $p)) { . $p } }\n");
    let tag = match style.rgb {
        Some((r, g, b)) => format!(
            "$([char]27)[38;2;{r};{g};{b}m[{}]$([char]27)[0m ",
            style.name
        ),
        None => format!("[{}] ", style.name),
    };
    s.push_str("$function:__hydra_prompt = $function:prompt\n");
    if style.integration {
        s.push_str(&pwsh_integration(&tag));
    } else {
        s.push_str(&format!(
            "function global:prompt {{ \"{tag}\" + (& $function:__hydra_prompt) }}\n"
        ));
    }
    s
}

pub fn render_bash_init(style: &PromptStyle) -> String {
    let mut s = header(style.name);
    s.push_str("[ -f /etc/profile ] && . /etc/profile\n");
    s.push_str("if [ -f ~/.bash_profile ]; then . ~/.bash_profile; elif [ -f ~/.bashrc ]; then . ~/.bashrc; fi\n");
    let tag = match style.rgb {
        Some((r, g, b)) => format!("\\[\\e[38;2;{r};{g};{b}m\\][{}]\\[\\e[0m\\] ", style.name),
        None => format!("[{}] ", style.name),
    };
    if style.integration {
        s.push_str(&format!(
            "PS1={}\"$PS1\"'\\[\\e]133;B\\a\\]'\n",
            sh_quote(&tag)
        ));
        s.push_str(BASH_INTEGRATION);
    } else {
        s.push_str(&format!("PS1={}\"$PS1\"\n", sh_quote(&tag)));
    }
    s
}

/// The `.zshrc` in hydra's ZDOTDIR (see `write_init_text`): the user's own `.zshrc`, then the
/// tagged prompt. ZDOTDIR goes back to the user's folder first, so zsh reads their `.zlogin`
/// next and their history file is the usual one.
pub fn render_zsh_init(style: &PromptStyle) -> String {
    let mut s = header(style.name);
    s.push_str(
        "ZDOTDIR=${__hydra_user_zdotdir:-$HOME}\n\
         unset __hydra_zdotdir __hydra_user_zdotdir\n\
         [[ -f \"$ZDOTDIR/.zshrc\" ]] && source \"$ZDOTDIR/.zshrc\"\n",
    );
    let tag = match style.rgb {
        Some((r, g, b)) => format!("%{{\\e[38;2;{r};{g};{b}m%}}[{}]%{{\\e[0m%}} ", style.name),
        None => format!("[{}] ", style.name),
    };
    s.push_str(&zsh_prompt(&tag, style.integration));
    s
}

/// hydra's ZDOTDIR `.zshenv`: the user's own (from $HOME), noting the folder it may have
/// moved ZDOTDIR to, where their other startup files are.
const ZSHENV: &str = r#"# generated by hydra: loads your own startup files; see .zshrc
__hydra_zdotdir=$ZDOTDIR
ZDOTDIR=$HOME
[[ -f "$ZDOTDIR/.zshenv" ]] && source "$ZDOTDIR/.zshenv"
__hydra_user_zdotdir=$ZDOTDIR
ZDOTDIR=$__hydra_zdotdir
"#;

/// hydra's ZDOTDIR `.zprofile` (login shells): the user's own.
const ZPROFILE: &str = r#"# generated by hydra: loads your own startup files; see .zshrc
ZDOTDIR=${__hydra_user_zdotdir:-$HOME}
[[ -f "$ZDOTDIR/.zprofile" ]] && source "$ZDOTDIR/.zprofile"
ZDOTDIR=$__hydra_zdotdir
"#;

/// zsh's tagged prompt, kept by a precmd hook that runs after the user's (themes rebuild
/// PROMPT before every prompt). With `integration`, hydraui's marks: the same sequence as
/// bash's, with D's exit code taken by a precmd hook that runs first.
fn zsh_prompt(tag: &str, integration: bool) -> String {
    let mut s = format!("__hydra_tag=$'{tag}'\nautoload -Uz add-zsh-hook\n");
    if integration {
        s.push_str(
            r#"__hydraui_b=$'%{\e]133;B\a%}'
__hydraui_precmd() {
  local ec=$?
  if [[ -n $__hydraui_ran ]]; then printf '\e]133;D;%s\a' "$ec"; fi
  __hydraui_ran=
  printf '\e]7;file://%s%s\a' "$HOST" "$PWD"
  printf '\e]133;A\a'
}
__hydraui_preexec() {
  __hydraui_ran=1
  printf '\e]133;C\a'
}
precmd_functions=(__hydraui_precmd $precmd_functions)
add-zsh-hook preexec __hydraui_preexec
__hydra_tag_prompt() {
  [[ $PROMPT == "$__hydra_tag"* ]] || PROMPT="$__hydra_tag$PROMPT"
  [[ $PROMPT == *"$__hydraui_b" ]] || PROMPT="$PROMPT$__hydraui_b"
}
"#,
        );
    } else {
        s.push_str(
            r#"__hydra_tag_prompt() {
  [[ $PROMPT == "$__hydra_tag"* ]] || PROMPT="$__hydra_tag$PROMPT"
}
"#,
        );
    }
    s.push_str("add-zsh-hook precmd __hydra_tag_prompt\n__hydra_tag_prompt\n");
    s
}

/// hydraui's pwsh prompt: OSC 133 D (last exit code, only after a command), OSC 7 (folder),
/// A, the tagged prompt, B; and OSC 133 C when a command line is accepted. Expects
/// `$function:__hydra_prompt` to hold the user's prompt.
fn pwsh_integration(tag: &str) -> String {
    let mut s = String::from(
        r#"function global:prompt {
  $ok = $global:?
  $code = if ($null -ne $global:__hydraui_code) { $global:__hydraui_code } elseif ($ok) { 0 } elseif ($global:LASTEXITCODE) { $global:LASTEXITCODE } else { 1 }
  $global:__hydraui_code = $null
  $e = [char]27; $b = [char]7; $out = ''
  if ($global:__hydraui_ran) { $out += "$e]133;D;$code$b" }
  $global:__hydraui_ran = $false
  $loc = $executionContext.SessionState.Path.CurrentLocation
  if ($loc.Provider.Name -eq 'FileSystem') { $out += "$e]7;file://$env:COMPUTERNAME/$($loc.ProviderPath -replace '\\', '/')$b" }
"#,
    );
    s.push_str(&format!(
        "  $out + \"$e]133;A$b\" + \"{tag}\" + (& $function:__hydra_prompt) + \"$e]133;B$b\"\n}}\n"
    ));
    s.push_str(
        r#"Import-Module PSReadLine -ErrorAction SilentlyContinue
if (Test-Path Function:\PSConsoleHostReadLine) {
  $global:__hydraui_readline = $function:PSConsoleHostReadLine
  function global:PSConsoleHostReadLine { $line = & $global:__hydraui_readline; $global:__hydraui_ran = $true; [Console]::Write("$([char]27)]133;C$([char]7)"); $line }
}
"#,
    );
    s
}

/// hydraui's bash prompt marks, the same sequence as pwsh's. The DEBUG trap fires C only for
/// the first command after a prompt: `__hydraui_armed` is set by the last PROMPT_COMMAND entry.
const BASH_INTEGRATION: &str = r#"__hydraui_prompt() {
  local ec=$?
  if [ -n "$__hydraui_ran" ]; then printf '\e]133;D;%s\a' "$ec"; fi
  __hydraui_ran=
  printf '\e]7;file://%s/%s\a' "$HOSTNAME" "$(pwd -W 2>/dev/null || pwd)"
  printf '\e]133;A\a'
  return $ec
}
__hydraui_preexec() {
  if [ -n "$__hydraui_armed" ]; then
    __hydraui_armed=
    __hydraui_ran=1
    printf '\e]133;C\a'
  fi
}
__hydraui_pc=${PROMPT_COMMAND%;}
PROMPT_COMMAND="__hydraui_prompt${__hydraui_pc:+;$__hydraui_pc};__hydraui_armed=1"
trap '__hydraui_preexec' DEBUG
"#;

/// The init script for `kind`, then `startup` (shell text, run as typed) when given. With
/// integration on, the startup command is marked as running so its exit code is reported.
pub fn render_init(kind: ShellKind, style: &PromptStyle, startup: Option<&str>) -> String {
    let mut s = match kind {
        ShellKind::Pwsh => render_pwsh_init(style),
        ShellKind::Bash => render_bash_init(style),
        ShellKind::Zsh => render_zsh_init(style),
    };
    if let Some(cmd) = startup {
        if style.integration {
            s.push_str(match kind {
                ShellKind::Pwsh => {
                    "$global:__hydraui_ran = $true; [Console]::Write(\"$([char]27)]133;C$([char]7)\")\n"
                }
                ShellKind::Bash | ShellKind::Zsh => "__hydraui_ran=1; printf '\\e]133;C\\a'\n",
            });
        }
        s.push_str(cmd);
        s.push('\n');
        if style.integration && kind == ShellKind::Pwsh {
            // The first prompt's `$?` describes the `-Command ". 'init.ps1'"` that ran this
            // script, not the startup command, so record the command's own status here.
            s.push_str(
                "$global:__hydraui_code = if ($?) { 0 } elseif ($LASTEXITCODE) { $LASTEXITCODE } else { 1 }\n",
            );
        }
    }
    s
}

/// Writes `state/<env>/shell/init.ps1`, `init.bash` or `init.zsh/` and returns the path
/// `shell_launch` takes.
pub fn write_init(
    kind: ShellKind,
    state_dir: &Path,
    style: &PromptStyle,
) -> std::io::Result<PathBuf> {
    let dir = state_dir.join("shell");
    std::fs::create_dir_all(&dir)?;
    write_init_text(kind, &dir.join("init"), &render_init(kind, style, None))
}

/// Writes `text` (from `render_init`) as `kind`'s init beside `stem`: `<stem>.ps1`,
/// `<stem>.bash`, or for zsh (which has no `--rcfile`) a ZDOTDIR `<stem>.zsh/` whose
/// `.zshenv` and `.zprofile` load the user's own and whose `.zshrc` is `text`. Returns the
/// path `shell_launch` takes.
pub fn write_init_text(kind: ShellKind, stem: &Path, text: &str) -> std::io::Result<PathBuf> {
    let beside = |ext: &str| {
        let mut name = stem.as_os_str().to_owned();
        name.push(ext);
        PathBuf::from(name)
    };
    let path = match kind {
        ShellKind::Pwsh => beside(".ps1"),
        ShellKind::Bash => beside(".bash"),
        ShellKind::Zsh => {
            let dir = beside(".zsh");
            std::fs::create_dir_all(&dir)?;
            std::fs::write(dir.join(".zshenv"), ZSHENV)?;
            std::fs::write(dir.join(".zprofile"), ZPROFILE)?;
            dir.join(".zshrc")
        }
    };
    std::fs::write(&path, text)?;
    Ok(path)
}

/// Arguments and extra variables that start `kind` running `init`, for callers that don't
/// use `std::process::Command` (hydraui's PTY).
pub fn shell_launch(
    kind: ShellKind,
    init: &Path,
) -> (Vec<OsString>, Vec<(&'static str, OsString)>) {
    match kind {
        ShellKind::Pwsh => (
            vec![
                "-NoLogo".into(),
                "-NoProfile".into(),
                "-NoExit".into(),
                "-Command".into(),
                format!(". '{}'", init.to_string_lossy().replace('\'', "''")).into(),
            ],
            vec![],
        ),
        ShellKind::Bash => (
            vec!["--rcfile".into(), to_msys(init).into(), "-i".into()],
            // Stops Git Bash's /etc/profile from cd-ing to ~.
            vec![("CHERE_INVOKING", "1".into())],
        ),
        // A login shell, as Terminal and iTerm start; zsh reads hydra's ZDOTDIR, which loads
        // the user's own files.
        ShellKind::Zsh => (
            vec!["-l".into(), "-i".into()],
            vec![(
                "ZDOTDIR",
                init.parent()
                    .unwrap_or(Path::new(""))
                    .as_os_str()
                    .to_owned(),
            )],
        ),
    }
}

pub fn shell_command(kind: ShellKind, exe: &Path, init: &Path) -> Command {
    let mut cmd = Command::new(exe);
    let (args, vars) = shell_launch(kind, init);
    cmd.args(args);
    for (k, v) in vars {
        cmd.env(k, v);
    }
    cmd
}

