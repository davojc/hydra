#[test]
fn bind_file_writes_a_hydra_file_and_unbind_removes_it() {
    let h = home();
    let c = h.dir.path().join("c");
    std::fs::create_dir_all(&c).unwrap();
    h.hydra()
        .args(["bind", "--file"])
        .arg(&c)
        .arg("personal")
        .assert()
        .success()
        .stdout(predicate::str::contains("env = \"personal\""));
    assert_eq!(
        std::fs::read_to_string(c.join(".hydra")).unwrap(),
        "# generated by hydra\nenv = \"personal\"\n"
    );
    h.hydra()
        .current_dir(&c)
        .arg("bind")
        .assert()
        .success()
        .stdout(predicate::str::contains("-> personal (.hydra in"));
    h.hydra().arg("unbind").arg(&c).assert().success();
    assert!(!c.join(".hydra").exists());
}

#[test]
fn bind_file_adds_to_git_exclude_in_a_repo() {
    let h = home();
    let repo = h.dir.path().join("repo");
    std::fs::create_dir_all(&repo).unwrap();
    assert!(
        std::process::Command::new("git")
            .args(["init", "-q"])
            .arg(&repo)
            .status()
            .unwrap()
            .success()
    );
    h.hydra()
        .args(["bind", "--file"])
        .arg(&repo)
        .arg("work")
        .assert()
        .success()
        .stdout(predicate::str::contains("added to .git/info/exclude"));
    let ex = std::fs::read_to_string(repo.join(".git/info/exclude")).unwrap();
    assert!(ex.lines().any(|l| l == ".hydra"), "{ex}");
}

