mod common;
use common::Home;
use predicates::prelude::*;

fn home() -> Home {
    let h = Home::new();
    h.write_env("work", "label = \"work\"\n");
    h.write_env("personal", "label = \"personal\"\n");
    h
}

fn config(h: &Home) -> String {
    std::fs::read_to_string(h.root().join("config.toml")).unwrap_or_default()
}

#[test]
fn bind_shows_lists_and_unbinds_a_folder_rule() {
    let h = home();
    let w = h.dir.path().join("w");
    let sub = w.join("sub");
    std::fs::create_dir_all(&sub).unwrap();

    h.hydra()
        .args(["bind"])
        .arg(&w)
        .arg("work")
        .assert()
        .success()
        .stdout(predicate::str::contains("bound"))
        .stdout(predicate::str::contains("-> work (rule"));
    assert!(config(&h).contains("work"), "{}", config(&h));

    h.hydra()
        .current_dir(&sub)
        .arg("bind")
        .assert()
        .success()
        .stdout(predicate::str::contains("-> work (rule"));

    h.hydra()
        .args(["bind", "--list"])
        .assert()
        .success()
        .stdout(predicate::str::contains("  ->  work"));

    h.hydra()
        .arg("unbind")
        .arg(&w)
        .assert()
        .success()
        .stdout(predicate::str::contains("removed rule"));
    assert!(!config(&h).contains("work"), "{}", config(&h));

    h.hydra()
        .arg("unbind")
        .arg(&w)
        .assert()
        .success()
        .stdout(predicate::str::contains("has no binding of its own"));

    h.hydra()
        .current_dir(&sub)
        .arg("bind")
        .assert()
        .success()
        .stdout(predicate::str::contains("isn't bound"));
}

